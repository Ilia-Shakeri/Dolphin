"""Write `scripts/verify-postgres-schema.sql` from the code itself (2.40.42).

The restore check (`verify-postgres-restore.sh` / `.ps1`) and the PostgreSQL
harness run that SQL against a database to prove it holds this release's
schema. It used to be written by hand and froze at the 1.x migration counts,
so on any 2.x database it failed — a restore check that rejects every good
backup. Now it is derived from what the code declares:

* every table of a first-party model (and its many-to-many tables);
* every migration of every installed app, recorded in `django_migrations`;
* every named check and unique constraint in `pg_constraint`, and every
  conditional unique constraint as a valid, live, partial unique index;
* a few hand-written shape checks of indexes whose exact predicate matters
  (kept from the original proof).

    python scripts/generate_schema_proof.py          # rewrite the file
    python scripts/generate_schema_proof.py --check  # exit 1 when it is stale

`common/tests/test_schema_proof.py` fails the suite when the committed file
no longer matches, so a migration cannot ship without it.
"""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "scripts" / "verify-postgres-schema.sql"

HEADER = """-- Generated by scripts/generate_schema_proof.py — do not edit by hand.
-- Proves a database holds this release's schema: its tables, its recorded
-- migrations, its named constraints and its partial unique indexes. Exits
-- non-zero (ON_ERROR_STOP=1) when any of them is missing.
"""

