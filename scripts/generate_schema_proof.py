def _setup():
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.test_settings")
    import django

    django.setup()


def _first_party_models():
    from django.apps import apps

    for config in sorted(apps.get_app_configs(), key=lambda item: item.label):
        if not Path(config.path).resolve().is_relative_to(ROOT):
            continue
        for model in config.get_models(include_auto_created=True):
            if model._meta.managed and not model._meta.proxy:
                yield model


def _values(rows, indent="                "):
    return ",\n".join(f"{indent}({', '.join(repr(part) for part in row)})" for row in rows)


def render():
    """The proof's full text, from the models and the migration graph."""
    _setup()
    from django.db.migrations.loader import MigrationLoader
    from django.db.models import UniqueConstraint

    models = list(_first_party_models())
    tables = sorted({model._meta.db_table for model in models})
    migrations = sorted(MigrationLoader(None, ignore_no_migrations=True).graph.nodes)
    constraints, partial_indexes = set(), set()
    for model in models:
        for constraint in model._meta.constraints:
            if isinstance(constraint, UniqueConstraint) and (constraint.condition is not None or constraint.expressions):
                partial_indexes.add((model._meta.db_table, constraint.name))
            else:
                constraints.add((model._meta.db_table, constraint.name))

    lines = [HEADER, "SELECT (\n"]
    lines.append("\n".join(
        f"    {'' if index == 0 else 'AND '}to_regclass('public.{table}') IS NOT NULL" for index, table in enumerate(tables)
    ) + "\n")
    lines.append(f"""    -- Every migration this release ships ({len(migrations)}), recorded.
    AND NOT EXISTS (
        SELECT 1
        FROM (
            VALUES
{_values(migrations)}
        ) AS required_migration(app, name)
        WHERE NOT EXISTS (
            SELECT 1
            FROM django_migrations
            WHERE django_migrations.app = required_migration.app
              AND django_migrations.name = required_migration.name
        )
    )
    -- Every named check and unique constraint ({len(constraints)}).
    AND NOT EXISTS (
        SELECT 1
        FROM (
            VALUES
{_values(sorted(constraints))}
        ) AS required_constraint(table_name, constraint_name)
        WHERE NOT EXISTS (
            SELECT 1
            FROM pg_constraint
            WHERE conrelid = to_regclass('public.' || required_constraint.table_name)
              AND conname = required_constraint.constraint_name
        )
    )
    -- Every conditional unique constraint ({len(partial_indexes)}). A UniqueConstraint
    -- with a condition is a partial unique index, absent from pg_constraint, so it
    -- is proven here: valid, live and unique.
    AND NOT EXISTS (
        SELECT 1
        FROM (
            VALUES
{_values(sorted(partial_indexes))}
        ) AS required_index(table_name, index_name)
        WHERE NOT EXISTS (
            SELECT 1
            FROM pg_class index_relation
            JOIN pg_namespace index_namespace
              ON index_namespace.oid = index_relation.relnamespace
            JOIN pg_index index_info
              ON index_info.indexrelid = index_relation.oid
            WHERE index_namespace.nspname = 'public'
              AND index_relation.relname = required_index.index_name
              AND index_info.indrelid = to_regclass('public.' || required_index.table_name)
              AND index_info.indisunique
              AND index_info.indisvalid
              AND index_info.indisready
              AND index_info.indislive
        )
    )
""")
    lines.append(INDEX_SHAPE_CHECKS)
    lines.append(FOOTER)
    return "".join(lines)


def main(argv):
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("scripts/verify-postgres-schema.sql is stale: run python scripts/generate_schema_proof.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
